#!/usr/bin/env node
// Generates precache.js (classic script imported by sw.js) from src/version.js and
// the repo's file tree. Run after adding/removing shipped files or bumping VERSION:
//
//   node tools/gen-precache.mjs
//
// tests/sw-precache.test.js fails when precache.js is stale.

import { readFileSync, readdirSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join, relative, sep } from "node:path";

export const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");

// Paths relative to the repo root (POSIX separators) that are never precached.
const EXCLUDED_DIRS = new Set(["node_modules", "tests", "tools", "docs", "src/ui/dev"]);
const EXCLUDED_FILES = new Set([
  "README.md", "package.json", "package-lock.json", "sw.js", "precache.js",
]);

export function readVersion(rootDir = ROOT) {
  const text = readFileSync(join(rootDir, "src", "version.js"), "utf8");
  const m = text.match(/VERSION\s*=\s*["'`]([^"'`]+)["'`]/);
  if (!m) throw new Error("could not find VERSION in src/version.js");
  return m[1];
}

function isExcluded(rel, isDir) {
  const name = rel.split("/").pop();
  if (name.startsWith(".")) return true; // .git, .github, .DS_Store, …
  if (isDir) return EXCLUDED_DIRS.has(rel);
  if (EXCLUDED_FILES.has(rel)) return true;
  if (name.endsWith(".md")) return true; // documentation is never shipped
  return false;
}

export function listFiles(rootDir = ROOT) {
  const out = [];
  const walk = (dir) => {
    for (const ent of readdirSync(dir, { withFileTypes: true })) {
      const abs = join(dir, ent.name);
      const rel = relative(rootDir, abs).split(sep).join("/");
      if (ent.isDirectory()) {
        if (!isExcluded(rel, true)) walk(abs);
      } else if (ent.isFile()) {
        if (!isExcluded(rel, false)) out.push(rel);
      }
    }
  };
  walk(rootDir);
  return out;
}

const byCodePoint = (a, b) => (a < b ? -1 : a > b ? 1 : 0);

/** -> { version, urls, source } — `source` is the exact text of precache.js. */
export function buildPrecache(rootDir = ROOT) {
  const version = readVersion(rootDir);
  const files = listFiles(rootDir).filter((f) => f !== "index.html").sort(byCodePoint);
  const urls = ["./", "./index.html", ...files.map((f) => `./${f}`)];
  const source =
    `// GENERATED by tools/gen-precache.mjs — do not edit by hand.\n` +
    `// Re-run \`node tools/gen-precache.mjs\` after adding files or bumping VERSION.\n` +
    `self.APP_VERSION = ${JSON.stringify(version)};\n` +
    `self.PRECACHE_URLS = [\n${urls.map((u) => `  ${JSON.stringify(u)},`).join("\n")}\n];\n`;
  return { version, urls, source };
}

export function main(rootDir = ROOT) {
  const { version, urls, source } = buildPrecache(rootDir);
  writeFileSync(join(rootDir, "precache.js"), source);
  console.log(`precache.js: version ${version}, ${urls.length} URLs`);
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) main();
